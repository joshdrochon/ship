/**
 * PF-804 evidence generator — re-runnable proof that the regression budget job
 * actually fails the PR.
 *
 *     pnpm baseline:evidence            # writes to .l26-evidence/
 *     node api/src/scripts/seed-regression-evidence.mjs <dir>
 *
 * PRD p.2 gate item 9 requires the three metrics to stay within +10% of the Part 1
 * baseline; p.18 asks whether that is enforced by "manual benchmark, automated
 * baseline comparison, perf job that fails the PR". PF-804's criterion is that a
 * job which has never been seen to fail is not evidence of one — so this seeds a
 * deliberate regression in each metric in turn and the operator observes three
 * separate non-zero exits.
 *
 * ── Why the regression is seeded into the BASELINE ───────────────────────────
 * `<dir>/current.json` is a real measurement of the working tree, produced by
 *
 *     pnpm baseline:compare -- --measure-out <dir>/current.json
 *
 * and it is reused unchanged as the numerator in every run below. Only the
 * denominator is doctored. Editing the measured values instead would prove the
 * comparator can subtract; it would not prove the job fails on a real run against
 * a real denominator.
 *
 * Writes five baselines:
 *
 *   baseline-control.json  identical to the measurement            -> job PASSES (exit 0)
 *   baseline-p95.json      one route's P95 divided by 1.11         -> +11%, exit 1
 *   baseline-bundle.json   gzip bytes divided by 1.11              -> +11%, exit 1
 *   baseline-queries.json  one route's query count minus one       -> +16.7%, exit 1
 *   baseline-empty.json    zero bytes                              -> BASELINE UNUSABLE, exit 1
 *
 * The control is not optional: a job only ever seen to fail is no better evidence
 * than one only ever seen to pass.
 *
 * Query counts are integers, so the smallest regression expressible on a 7-query
 * route is 7 -> 8 (+14.3%). That is the ~11%-class regression this metric can
 * express — there is no fractional query.
 *
 * Then, for each baseline:
 *
 *     pnpm baseline:compare -- --current <dir>/current.json \
 *                              --baseline <dir>/baseline-<metric>.json \
 *                              --strict-latency          # p95 run only
 *
 * `--strict-latency` is needed for the P95 run when the machine is under load,
 * because the load guard otherwise (correctly) downgrades latency to advisory.
 * The bundle and query runs need no such flag: both metrics are deterministic and
 * enforced unconditionally.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = process.argv[2] ?? '.l26-evidence';
const current = JSON.parse(readFileSync(join(DIR, 'current.json'), 'utf8'));

const P95_ROUTE = 'GET /api/documents';
const QUERY_ROUTE = 'GET /api/dashboard/my-work';

const clone = (x) => JSON.parse(JSON.stringify(x));

function baselineFrom(routes, bundle) {
  return {
    $schema: 'https://ship.internal/schemas/baseline-part1.json',
    _comment:
      'PF-804 EVIDENCE FIXTURE — a deliberately doctored denominator, generated by ' +
      'api/src/scripts/seed-regression-evidence.mjs. NOT the real baseline.',
    capturedAt: '2026-08-13T00:00:00.000Z',
    gitRef: 'pf804-evidence-fixture',
    method: current.method,
    budget: {
      maxRegressionPercent: 10,
      appliesTo: ['latencyMs.p95 per route', 'bundle.totalGzipBytes', 'queriesPerRequest per route'],
      source: 'PRD p.2 (MVP gate item 9), p.6 (Performance Targets)',
    },
    summary: {
      routeCount: Object.keys(routes).length,
      worstP95Ms: Math.max(...Object.values(routes).map((r) => r.latencyMs.p95)),
      totalQueriesAcrossRoutes: Object.values(routes).reduce((a, r) => a + r.queriesPerRequest, 0),
      bundleTotalGzipBytes: bundle.totalGzipBytes,
    },
    routes,
    bundle,
  };
}

const write = (name, obj) => writeFileSync(join(DIR, name), JSON.stringify(obj, null, 2) + '\n');

write('baseline-control.json', baselineFrom(clone(current.routes), clone(current.bundle)));

{
  const routes = clone(current.routes);
  routes[P95_ROUTE].latencyMs.p95 = Number((routes[P95_ROUTE].latencyMs.p95 / 1.11).toFixed(2));
  write('baseline-p95.json', baselineFrom(routes, clone(current.bundle)));
}

{
  const bundle = clone(current.bundle);
  bundle.totalGzipBytes = Math.round(bundle.totalGzipBytes / 1.11);
  write('baseline-bundle.json', baselineFrom(clone(current.routes), bundle));
}

{
  const routes = clone(current.routes);
  routes[QUERY_ROUTE].queriesPerRequest -= 1;
  write('baseline-queries.json', baselineFrom(routes, clone(current.bundle)));
}

writeFileSync(join(DIR, 'baseline-empty.json'), '');

console.log(`wrote control, p95, bundle, queries and empty baselines to ${DIR}/`);
